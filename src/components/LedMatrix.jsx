/* Glyph path at any scale: each font pixel becomes a scale × scale block of
   LEDs. Exported for the gallery boards. */
export function textPath(text, x0, top, scale = 1) {
  const adv = 6 * scale;
  let d = '';
  [...text].forEach((ch, i) => {
    const g = FONT[ch] || FONT[ch.toUpperCase()] || FONT[' '];
    g.forEach((row, y) => {
      for (let x = 0; x < 5; x++) {
        if (row[x] === '1') d += `M${x0 + i * adv + x * scale} ${top + y * scale}h${scale}v${scale}h-${scale}z`;
      }
    });
  });
  return d;
}
export const textWidth = (text, scale = 1) => [...text].length * 6 * scale - scale;

const COLS = 128;            // four P10 panels wide
const SCALE = 2;             // each glyph pixel = 2 × 2 LEDs
const ADVANCE = 6 * SCALE;   // 5 columns + 1 gap

function glyphPath(text, x0, top) {
  let d = '';
  [...text].forEach((ch, i) => {
    const g = FONT[ch] || FONT[ch.toUpperCase()] || FONT[' '];
    g.forEach((row, y) => {
      for (let x = 0; x < 5; x++) {
        if (row[x] === '1') d += `M${x0 + i * ADVANCE + x * SCALE} ${top + y * SCALE}h2v2h-2z`;
      }
    });
  });
  return d;
}

/* `lines`: one per panel row (16 LEDs tall). A line with `scroll` loops
   right-to-left; the others are centred and static. Default is the first
   real build: a 4 × 3 board, 12 panels. */
const DEFAULT_LINES = [
  { text: 'ANANTA IONS · CAMPUS DISPLAY NETWORK · ', scroll: true },
  { text: 'NOTICES' },
  { text: 'TIMETABLES' },
];

/* Kept for older call sites: draws through LedBoard, so every P10 board on
   the site has the same LEDs, frame, seams and colours. One line = one
   panel row (16 LEDs); four panels wide. */
export default function LedMatrix({ lines = DEFAULT_LINES, id = 'led', colour = 'amber' }) {
  const items = lines.map((l, i) => ({ text: l.text, size: 2, y: i * 16 + 1, effect: l.scroll ? 'scroll' : 'static' }));
  return <LedBoard id={id} panels={[4, lines.length]} items={items} colour={colour} />;
}
